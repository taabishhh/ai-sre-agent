from agent.config import SETTINGS

STATUS_TEXT = {
    "approved": "✅ Approved and applied",
    "auto_approved": "✅ Auto-approved and applied",
    "denied": "⛔ Denied by reviewer, no changes made",
    "pending": "⏳ Waiting for review",
}


def format_summary(diagnosis, proposal, approval_status, execution_result, namespace):
    evidence = "\n".join(f"- {item}" for item in diagnosis["evidence"])
    status = STATUS_TEXT.get(approval_status, approval_status)

    if SETTINGS.anthropic_api_key:
        footer = f"_Generated by Claude ({SETTINGS.anthropic_model})._"
    else:
        footer = "_No ANTHROPIC_API_KEY set, so this run used canned demo answers._"

    return f"""### AI SRE Incident Summary — namespace `{namespace}`

**Root cause**
{diagnosis['root_cause']}

**Evidence**
{evidence}

**Confidence:** {diagnosis['confidence']}
**Affected resources:** {', '.join(diagnosis['affected_resources'])}

---

**Proposed fix:** `{proposal['action']}` (params: `{proposal['params']}`)
**Rationale:** {proposal['rationale']}
**Risk level:** {proposal['risk_level']}
**Expected outcome:** {proposal['expected_outcome']}

**Status:** {status}

**Execution result:**
```
{execution_result or '(not executed)'}
```

{footer}
"""
